const translations: Record<AppLanguage, Record<TranslationKey, string>> = {
  en: enTranslations,
  "zh-Hant": zhHantTranslations,
  "zh-Hans": zhHansTranslations,
};

export const appLanguageHtmlLang: Record<AppLanguage, string> = {
  en: "en",
  "zh-Hant": "zh-Hant",
  "zh-Hans": "zh-Hans",
};

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === "en" || value === "zh-Hant" || value === "zh-Hans";
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  replacements: Record<string, string | number> = {},
) {
  const template = translations[language][key] ?? zhHantTranslations[key] ?? key;

  return Object.entries(replacements).reduce(
    (text, [replacementKey, replacementValue]) =>
      text.split(`{${replacementKey}}`).join(String(replacementValue)),
    template,
  );
}

export function createTranslator(language: AppLanguage) {
  return (key: TranslationKey, replacements?: Record<string, string | number>) =>
    translate(language, key, replacements);
}
